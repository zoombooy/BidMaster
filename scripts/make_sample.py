"""生成一份贴近真实形态的示例招标文件 .docx，用于测试与演示。

覆盖：封面 / 招标公告 / 投标人须知前附表（字段金矿）/ 评标办法与评分细则表
（技术 60 + 商务 30 + 价格 10）/ ★实质性条款 / 暗标要求。
"""
from __future__ import annotations

from pathlib import Path


def build_sample_docx(out_path: str | Path = "evals/golden/sample_tender.docx") -> Path:
    from docx import Document

    doc = Document()

    def h(level: int, text: str):
        doc.add_heading(text, level=level)

    def p(text: str):
        doc.add_paragraph(text)

    def table(rows: list[list[str]]):
        t = doc.add_table(rows=len(rows), cols=len(rows[0]))
        t.style = "Table Grid"
        for i, row in enumerate(rows):
            for j, val in enumerate(row):
                t.cell(i, j).text = val
        return t

    # 封面
    p("某某市第三人民医院住院综合楼建设项目施工招标")
    p("招标编号：XYZ-2026-GC-001")
    p("招标人：某某市第三人民医院")
    p("二〇二六年九月")

    # 第一章 招标公告
    h(1, "第一章 招标公告")
    p("1. 招标条件")
    p("本招标项目某某市第三人民医院住院综合楼建设项目已由某某市发展和改革委员会批准建设，"
      "项目名称：某某市第三人民医院住院综合楼建设项目，招标编号：XYZ-2026-GC-001。"
      "招标人为某某市第三人民医院，建设资金来源：财政资金，项目出资比例为100%。"
      "项目已具备招标条件，现对该项目施工进行公开招标。")
    p("2. 项目概况与招标范围")
    p("建设地点：某某市高新区健康大道88号。")
    p("建设规模：总建筑面积约52000平方米，地上12层、地下2层。")
    p("计划工期：540日历天。")
    p("质量标准：符合国家现行施工质量验收规范合格标准。")
    p("招标范围：施工图纸范围内的建筑工程、装饰装修、给排水及暖通电气安装工程。")
    p("3. 投标人资格要求")
    p("3.1 具有独立法人资格，具备建筑工程施工总承包一级及以上资质，并处于有效期内。")
    p("3.2 拟派项目负责人（项目经理）须具备建筑工程专业一级注册建造师执业资格，"
      "具有有效的安全生产考核合格证书（B证），且无在建工程。")
    p("3.3 近5年内须完成至少2项单项合同金额5000万元及以上的同类房屋建筑工程业绩。")
    p("4. 招标文件的获取")
    p("2026年10月10日至2026年10月17日，登录某某市公共资源交易平台下载招标文件。")
    p("5. 投标文件的递交")
    p("投标文件递交截止时间（即投标截止时间，下同）为2026年11月20日09时30分，"
      "递交地点为某某市公共资源交易中心第三开标室。")
    p("6. 最高投标限价：人民币贰亿伍仟万元整（¥250,000,000.00）。")

    # 第二章 投标人须知
    h(1, "第二章 投标人须知")
    h(2, "投标人须知前附表")
    table([
        ["条款名称", "编列内容"],
        ["招标人", "某某市第三人民医院"],
        ["招标代理机构", "华信工程咨询有限公司"],
        ["项目名称", "某某市第三人民医院住院综合楼建设项目"],
        ["招标编号", "XYZ-2026-GC-001"],
        ["资金来源", "财政资金"],
        ["最高投标限价", "人民币贰亿伍仟万元整（¥250,000,000.00）"],
        ["计划工期", "540 日历天"],
        ["质量标准", "合格"],
        ["投标有效期", "自投标截止之日起90日历天"],
        ["投标保证金", "人民币捌拾万元整（¥800,000.00）"],
        ["投标截止时间", "2026年11月20日09时30分"],
        ["开标时间", "2026年11月20日09时30分"],
        ["是否采用电子招标", "采用电子招投标，不接收纸质文件"],
    ])
    p("1. 总则：本招标文件仅适用于本次投标。")
    p("2. 招标文件由招标文件、补遗书、答疑纪要组成，相互矛盾时以后发出者为准。")
    p("3. 投标文件的编制：投标人应按第八章规定的格式编制投标文件，技术标采用暗标形式编制。")

    # 第三章 评标办法
    h(1, "第三章 评标办法")
    h(2, "评标办法前附表")
    table([
        ["条款名称", "编列内容"],
        ["评标办法", "综合评估法"],
        ["技术标分值", "60分"],
        ["商务标分值", "30分"],
        ["价格标分值", "10分"],
    ])
    h(2, "评分细则")
    p("评标委员会按以下评分细则打分，满分100分。技术标60分、商务标30分、价格标10分。")
    table([
        ["序号", "评分项", "分值", "评分标准"],
        ["技术标（60分）", "", "", ""],
        ["1", "类似工程业绩", "6", "近5年每提供1项单项合同金额5000万元以上的同类房屋建筑工程业绩得2分，最多6分。需提供中标通知书、合同协议书、竣工验收证明复印件。"],
        ["2", "施工组织设计", "20", "施工方案完整可行、进度计划合理、平面布置科学：优16-20分，良12-15分，一般8-11分，差0-7分。"],
        ["3", "项目负责人", "10", "项目负责人具备建筑工程专业一级注册建造师且具有高级工程师职称的得4分；近5年主持完成1项单项合同金额5000万元以上同类工程业绩的得3分；无在建工程得3分。需提供注册证书、职称证、社保证明、业绩证明。"],
        ["4", "工作组人员配备", "14", "技术负责人具有高级工程师职称得4分；配备安全员2名且均具有安全生产考核合格证（B证）得5分；配备注册造价工程师1名得5分。需提供证书及社保证明。"],
        ["5", "质量保证与安全文明", "10", "质量保证体系健全、安全文明施工措施完善：优8-10分，良6-7分，一般4-5分，差0-3分。"],
        ["商务标（30分）", "", "", ""],
        ["6", "企业资质与认证", "8", "具有ISO9001质量管理体系认证得3分；ISO14001环境管理体系认证得2分；ISO45001职业健康安全管理体系认证得3分。需提供证书。"],
        ["7", "财务状况", "8", "提供近三年（2023-2025年度）经会计师事务所审计的财务报告，每年得2分，最多6分；纳税信用等级为A级的得2分。需提供审计报告及纳税证明。"],
        ["8", "企业信用", "6", "信用中国网站无失信被执行人记录得3分；无重大税收违法案件记录得3分。"],
        ["9", "企业荣誉", "8", "近3年获得省级及以上优质工程奖项每项得4分，最多8分。需提供获奖证书。"],
        ["价格标（10分）", "", "", ""],
        ["10", "投标报价", "10", "价格分=（评标基准价/投标报价）×10。评标基准价为通过初步评审的有效投标报价的算术平均值。"],
    ])
    p("说明：1. 技术标采用暗标形式编制，页数不得超过120页，字体采用仿宋GB2312小四号字，"
      "文中不得出现投标人单位名称、人员姓名及其他任何身份标识，否则作废标处理。")
    p("2. 带★号条款为实质性要求，不满足将导致投标被否决。")

    # 第四章 合同主要条款
    h(1, "第四章 合同主要条款")
    p("采用《建设工程施工合同（示范文本）》GF-2017-0201，专用条款详见合同附件。")

    # 第五章 技术标准和要求
    h(1, "第五章 技术标准和要求")
    p("★ 投标人须承诺在计划工期540日历天内完成全部施工内容并竣工验收合格。")
    p("★ 本工程采用装配式建筑技术，预制率不低于30%，投标人须具备相应施工能力。")
    p("技术标准执行现行国家、行业及地方标准；工程质量不合格的，投标人应无条件返工。")

    # 第六章 投标文件格式
    h(1, "第六章 投标文件格式")
    p("投标文件包括投标函、法定代表人身份证明、授权委托书、投标保证金缴纳凭证、"
      "已标价工程量清单、技术标、商务标等格式，详见附件。")

    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    doc.save(out)
    return out


if __name__ == "__main__":
    path = build_sample_docx()
    print(f"示例招标文件已生成: {path}")
